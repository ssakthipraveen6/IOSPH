#!/usr/bin/env node
/**
 * scripts/generate_shipper_configs.js
 *
 * T3b.2: Generates per-host log shipper configurations directly from the
 * Phase 1 entity model (@sentinel/inventory), ensuring paths, tags, and destinations
 * are never hand-maintained.
 */

const fs = require('fs');
const path = require('path');
const inventory = require('@sentinel/inventory');

// Writes one Fluent Bit config per host.
async function generateConfigs(targetEnv = 'staging', outputDir = null) {
  console.log(`[CONFIG_GEN] Generating Fluent Bit shipper configurations for env=${targetEnv}...`);
  const res = await inventory.getEntities({ environment: targetEnv, limit: 1000 });
  const entities = Array.isArray(res) ? res : (res.entities || []);
  const hosts = entities.filter(e => e.kind === 'host' || e.kind === 'agent');

  const outPath = outputDir || path.resolve(__dirname, '../deployments/generated_configs', targetEnv);
  if (!fs.existsSync(outPath)) {
    fs.mkdirSync(outPath, { recursive: true });
  }

  const generatedFiles = [];

  for (const host of hosts) {
    const hostName = host.name || host.id.replace(/^host:|^agent:/, '');
    const logPaths = host.attributes?.log_paths || [
      `/var/log/apps/${hostName}/*.log`,
      `/opt/sentinel/logs/${hostName}.log`
    ];

    const configContent = `
# Automatically generated by Sentinel Inventory Config Generator (T3b.2)
# Host: ${host.id} | Kind: ${host.kind} | Environment: ${targetEnv}
# Generated: ${new Date().toISOString()}

[SERVICE]
    Flush         2
    Log_Level     info
    Daemon        off
    Parsers_File  /etc/fluent-bit/parsers.conf

[INPUT]
    Name              tail
    Tag               app.${hostName}
    Path              ${logPaths.join(',')}
    DB                /var/log/fluentbit_${hostName}.db
    Mem_Buf_Limit     32MB

[FILTER]
    Name              modify
    Match             *
    Add               host.name ${hostName}
    Add               entity_id ${host.id}
    Add               deployment.environment ${targetEnv}
    Add               region ${host.region || 'emea'}

[OUTPUT]
    Name              http
    Match             *
    Host              sentinel.yourbank.internal
    Port              443
    URI               /v1/logs
    Format            json
    Header            X-Sentinel-Environment ${targetEnv}
    Tls               On
    Tls.verify        On
`.trim();

    const filePath = path.join(outPath, `${hostName}.conf`);
    fs.writeFileSync(filePath, configContent, 'utf8');
    generatedFiles.push({ host: host.id, file: filePath });
  }

  console.log(`[CONFIG_GEN] Successfully generated ${generatedFiles.length} host configs in ${outPath}`);
  return {
    environment: targetEnv,
    count: generatedFiles.length,
    outputDirectory: outPath,
    configs: generatedFiles
  };
}

if (require.main === module) {
  const env = process.argv[2] || 'staging';
  generateConfigs(env).catch(err => {
    console.error('[CONFIG_GEN] Error:', err);
    process.exit(1);
  });
}

module.exports = { generateConfigs };
