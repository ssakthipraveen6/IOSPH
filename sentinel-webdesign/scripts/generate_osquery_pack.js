#!/usr/bin/env node
/**
 * scripts/generate_osquery_pack.js  (npm run agent:osquery-pack)
 *
 * Phase A5: builds the osquery file-change packs from the `watch:` paths in
 * config/apps/*.yaml. Each product becomes one file_paths category named after the
 * product id, so a file event's `category` tells SENTINEL which product changed.
 *
 *   agent/osquery/packs/file-changes.conf          Linux   (file_events, inotify)
 *   agent/osquery/packs/file-changes-windows.conf  Windows (ntfs_journal_events)
 *
 * Usage: node scripts/generate_osquery_pack.js [--check]
 *   --check  exit 1 if the committed packs differ from what the manifests produce.
 */

const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const ROOT = path.join(__dirname, '..');
const APPS_DIR = path.join(ROOT, 'config', 'apps');
const PACK_DIR = path.join(ROOT, 'agent', 'osquery', 'packs');

// Host-level paths watched on every server, independent of products.
const BASE_PATHS = {
  linux: {
    system_binaries: ['/usr/bin/%%', '/usr/sbin/%%', '/bin/%%', '/sbin/%%'],
    ssl_certificates: ['/etc/ssl/certs/%%', '/etc/pki/tls/certs/%%'],
    sentinel_agent: ['/etc/sentinel/%%', '/opt/sentinel/%%']
  },
  windows: {
    sentinel_agent: ['C:\\Program Files\\SentinelAgent\\%%', 'C:\\ProgramData\\SentinelAgent\\config\\%%']
  }
};

// Watch paths from the manifests.
function loadWatchPaths(appsDir = APPS_DIR) {
  const out = { linux: {}, windows: {} };
  const files = fs.readdirSync(appsDir).filter(f => !f.startsWith('_') && /\.ya?ml$/.test(f)).sort();
  for (const file of files) {
    const doc = yaml.load(fs.readFileSync(path.join(appsDir, file), 'utf8')) || {};
    if (!doc.id || !doc.watch) continue;
    for (const os of ['linux', 'windows']) {
      const list = Array.isArray(doc.watch[os]) ? doc.watch[os].filter(p => typeof p === 'string' && p.trim()) : [];
      if (list.length) out[os][doc.id] = list;
    }
  }
  return out;
}

// Certificate paths from the manifests.
function loadCertificatePaths(appsDir = APPS_DIR) {
  const paths = [];
  const files = fs.readdirSync(appsDir).filter(f => !f.startsWith('_') && /\.ya?ml$/.test(f)).sort();
  for (const file of files) {
    const doc = yaml.load(fs.readFileSync(path.join(appsDir, file), 'utf8')) || {};
    if (!doc.certificates || !Array.isArray(doc.certificates.paths)) continue;
    for (const p of doc.certificates.paths) {
      if (typeof p === 'string' && p.trim() && !paths.includes(p.trim())) {
        paths.push(p.trim());
      }
    }
  }
  return paths;
}

// Builds the osquery packs.
function buildPacks(watch, certPaths = loadCertificatePaths()) {
  const header = 'Generated by scripts/generate_osquery_pack.js from config/apps/*.yaml watch: paths. Do not edit by hand.';
  const linux = {
    description: header,
    platform: 'linux',
    file_paths: { ...BASE_PATHS.linux, ...watch.linux },
    queries: {
      file_events: {
        query: 'SELECT target_path, category, action, md5, sha256, uid, time FROM file_events;',
        interval: 30,
        removed: false,
        description: 'File creation, modification and deletion under the watched paths'
      }
    }
  };
  const windows = {
    description: header,
    platform: 'windows',
    file_paths: { ...BASE_PATHS.windows, ...watch.windows },
    queries: {
      file_events: {
        query: 'SELECT path AS target_path, category, action, old_path, time FROM ntfs_journal_events;',
        interval: 30,
        removed: false,
        description: 'NTFS journal changes under the watched paths'
      }
    }
  };

  const linuxCertPathClauses = ["path LIKE '/etc/ssl/certs/%'"];
  for (const p of certPaths) {
    const normalized = p.replace(/\/+$/, '');
    linuxCertPathClauses.push(`path LIKE '${normalized}/%'`);
  }
  const linuxCertQuery = `SELECT common_name, subject, issuer, not_valid_after, path FROM certificates WHERE ${linuxCertPathClauses.join(' OR ')};`;

  const inventoryLinux = {
    description: 'System inventory pack for Linux (processes, packages, certificates, deleted file handles)',
    platform: 'linux',
    queries: {
      processes: {
        query: 'SELECT pid, parent AS ppid, state, start_time, on_disk, uid, cmdline, md5(cmdline) AS cmdline_hash FROM processes;',
        interval: 300,
        description: 'Process inventory with parent pid and cmdline hash'
      },
      certificates: {
        query: linuxCertQuery,
        interval: 300,
        description: 'Linux TLS certificates from /etc/ssl/certs and manifest paths'
      },
      deb_packages: {
        query: 'SELECT name, version, arch, revision FROM deb_packages;',
        interval: 300,
        description: 'Debian/Ubuntu package inventory for SBOM'
      },
      rpm_packages: {
        query: 'SELECT name, version, release, arch FROM rpm_packages;',
        interval: 300,
        description: 'RHEL/CentOS RPM package inventory for SBOM'
      },
      process_open_files: {
        query: "SELECT pid, fd, path FROM process_open_files WHERE path LIKE '%(deleted)%';",
        interval: 300,
        description: 'Open file descriptors pointing to deleted files'
      }
    }
  };

  const inventoryWindows = {
    description: 'System inventory pack for Windows (processes, services, programs, certificates, deleted file handles)',
    platform: 'windows',
    queries: {
      processes: {
        query: 'SELECT pid, parent AS ppid, state, start_time, on_disk, uid, cmdline, md5(cmdline) AS cmdline_hash FROM processes;',
        interval: 300,
        description: 'Process inventory with parent pid and cmdline hash'
      },
      services: {
        query: 'SELECT name, display_name, status, start_type FROM services;',
        interval: 300,
        description: 'Windows services inventory with start type and status'
      },
      certificates: {
        query: "SELECT common_name, subject, issuer, not_valid_after, store, store_location FROM certificates WHERE store IN ('My', 'Root');",
        interval: 300,
        description: 'Windows certificates from My and Root stores'
      },
      programs: {
        query: 'SELECT name, version, install_location, publisher FROM programs;',
        interval: 300,
        description: 'Installed Windows programs for SBOM'
      },
      process_open_files: {
        query: "SELECT pid, fd, path FROM process_open_files WHERE path LIKE '%(deleted)%';",
        interval: 300,
        description: 'Open file handles pointing to deleted files'
      }
    }
  };

  return {
    'file-changes.conf': JSON.stringify(linux, null, 2) + '\n',
    'file-changes-windows.conf': JSON.stringify(windows, null, 2) + '\n',
    'system-inventory.conf': JSON.stringify(inventoryLinux, null, 2) + '\n',
    'system-inventory-windows.conf': JSON.stringify(inventoryWindows, null, 2) + '\n'
  };
}

// Writes the packs, or checks them with --check.
function main(argv = process.argv.slice(2)) {
  const check = argv.includes('--check');
  const packs = buildPacks(loadWatchPaths(), loadCertificatePaths());
  let drift = false;
  for (const [name, content] of Object.entries(packs)) {
    const target = path.join(PACK_DIR, name);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;
    if (check) {
      if (current !== content) {
        drift = true;
        console.error(`[osquery-pack] ${path.relative(ROOT, target)} is out of date; run npm run agent:osquery-pack`);
      }
    } else {
      fs.writeFileSync(target, content);
      console.log(`[osquery-pack] wrote ${path.relative(ROOT, target)}`);
    }
  }
  return drift ? 1 : 0;
}

module.exports = { loadWatchPaths, loadCertificatePaths, buildPacks, BASE_PATHS };

if (require.main === module) process.exit(main());
