/**
 * On-call rota: loads, edits and saves the team rotas (.runtime/team_rota.json).
 */
const fs = require('fs');
const path = require('path');

// SENTINEL_RUNTIME_DIR lets tests use a throwaway folder instead of the real .runtime.
const RUNTIME_DIR = process.env.SENTINEL_RUNTIME_DIR
  ? path.resolve(process.env.SENTINEL_RUNTIME_DIR)
  : path.resolve(__dirname, '../.runtime');
const ROTA_FILE = path.join(RUNTIME_DIR, 'team_rota.json');
// Older versions kept the rota in one of these; read once if the runtime file does not exist yet
// (not under tests, which must start clean).
const LEGACY_ROTA_FILES = process.env.SENTINEL_RUNTIME_DIR ? [] : [
  path.resolve(__dirname, '../database/team_rota.json'),
  path.resolve(__dirname, '../../.runtime/team_rota.json')
];
const ROTA_HEADERS = ['Date', 'Day', 'Shift ID', 'Shift Name', 'Primary On-Call', 'Primary Email', 'Primary Pager',
  'Secondary On-Call', 'Escalation Manager', 'Location / Hub', 'Status', 'Handover Notes'];

/**
 * Blank month for the upload template: one row per day with the date filled in and every
 * person, shift and note left empty for the team to complete. Nothing here is shown as a rota.
 */
function blankMonthTemplate(category = 'core', forDate = new Date()) {
  const daysOfWeek = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  const year = forDate.getFullYear();
  const month = forDate.getMonth();
  const daysInMonth = new Date(year, month + 1, 0).getDate();
  const monthStr = String(month + 1).padStart(2, '0');
  const rows = [];
  for (let day = 1; day <= daysInMonth; day++) {
    const row = Object.fromEntries(ROTA_HEADERS.map(h => [h, '']));
    row.Date = `${year}-${monthStr}-${String(day).padStart(2, '0')}`;
    row.Day = daysOfWeek[new Date(year, month, day).getDay()];
    row['Shift ID'] = `${category.toUpperCase()}-${year}-${monthStr}${String(day).padStart(2, '0')}`;
    rows.push(row);
  }
  return rows;
}

// Rows seeded or generated by older versions used made-up people at these domains; they are not a rota.
function isGeneratedRow(row) {
  return /@(sentinel\.local|yourbank\.internal)$/i.test(String((row && row['Primary Email']) || ''));
}

// The three rotas exist with no rows until the team uploads one; nothing is generated.
function emptyRotas() {
  return {
    core: {
      name: "Core Operations 24/7 SRE Rota",
      category: "core",
      month: null,
      description: "Follow-the-Sun Global Escalation Roster for critical incidents and P1/P2 outages.",
      tableRows: []
    },
    bau: {
      name: "BAU (Business As Usual) Operations Rota",
      category: "bau",
      month: null,
      description: "Day-to-day platform maintenance, scheduled OS patching, access approvals, and service ticket handling.",
      tableRows: []
    },
    montreal: {
      name: "Montreal Regional On-Call Rota",
      category: "montreal",
      month: null,
      description: "Montreal Hub dedicated infrastructure, Eastern Time coverage, bilingual French/English support.",
      tableRows: []
    }
  };
}

// Reads the rota file, or the legacy one, or null.
function readRotaFile() {
  for (const file of [ROTA_FILE, ...LEGACY_ROTA_FILES]) {
    if (!fs.existsSync(file)) continue;
    try {
      const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
      if (parsed && parsed.core && parsed.bau && parsed.montreal) return parsed;
    } catch (err) {
      console.error('[TEAM ROTA] Error reading rota file:', err.message);
    }
  }
  return null;
}

// Loads all rotas. Rows that older versions generated are dropped, so only an uploaded rota is shown.
function loadAllRotas() {
  const parsed = readRotaFile();
  if (!parsed) return emptyRotas();
  let changed = false;
  for (const key of ['core', 'bau', 'montreal']) {
    const rows = Array.isArray(parsed[key].tableRows) ? parsed[key].tableRows : [];
    const kept = rows.filter(r => !isGeneratedRow(r));
    if (kept.length !== rows.length || !Array.isArray(parsed[key].tableRows)) changed = true;
    parsed[key].tableRows = kept;
    if (kept.length === 0) parsed[key].month = null;
  }
  if (changed || !fs.existsSync(ROTA_FILE)) saveAllRotas(parsed);
  return parsed;
}

// Saves all rotas.
function saveAllRotas(rotas) {
  try {
    fs.mkdirSync(RUNTIME_DIR, { recursive: true });
    fs.writeFileSync(ROTA_FILE, JSON.stringify(rotas, null, 2), 'utf8');
    return true;
  } catch (err) {
    console.error('[TEAM ROTA] Error writing rota file:', err.message);
    return false;
  }
}

/**
 * Robust RFC 4180 CSV serializer
 */
function serializeToCsv(rows) {
  if (!rows || rows.length === 0) return '';
  const headers = Object.keys(rows[0]);

  function escapeCsvCell(val) {
    if (val === null || val === undefined) return '';
    const str = String(val);
    if (str.includes(',') || str.includes('"') || str.includes('\n') || str.includes('\r')) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  }

  const csvLines = [headers.map(escapeCsvCell).join(',')];
  for (const row of rows) {
    csvLines.push(headers.map(h => escapeCsvCell(row[h])).join(','));
  }
  return csvLines.join('\r\n');
}

/**
 * Robust RFC 4180 CSV parser
 */
function parseCsvString(csvText) {
  const lines = [];
  let row = [];
  let cell = '';
  let inQuotes = false;

  for (let i = 0; i < csvText.length; i++) {
    const ch = csvText[i];
    const nextCh = csvText[i + 1];

    if (inQuotes) {
      if (ch === '"' && nextCh === '"') {
        cell += '"';
        i++; // skip escaped quote
      } else if (ch === '"') {
        inQuotes = false;
      } else {
        cell += ch;
      }
    } else {
      if (ch === '"') {
        inQuotes = true;
      } else if (ch === ',') {
        row.push(cell.trim());
        cell = '';
      } else if (ch === '\r') {
        // ignore CR
      } else if (ch === '\n') {
        row.push(cell.trim());
        cell = '';
        if (row.some(c => c.length > 0)) {
          lines.push(row);
        }
        row = [];
      } else {
        cell += ch;
      }
    }
  }

  if (cell.length > 0 || row.length > 0) {
    row.push(cell.trim());
    if (row.some(c => c.length > 0)) {
      lines.push(row);
    }
  }

  if (lines.length === 0) return [];
  const headers = lines[0];
  const result = [];

  for (let r = 1; r < lines.length; r++) {
    const dataRow = lines[r];
    const obj = {};
    for (let c = 0; c < headers.length; c++) {
      obj[headers[c]] = dataRow[c] !== undefined ? dataRow[c] : '';
    }
    result.push(obj);
  }

  return result;
}

/**
 * Parses an uploaded CSV / tabular rota file buffer and applies all rows into the designated rota.
 * [T0.19 / D7] Replaces vulnerable xlsx library with native hand-rolled CSV parser.
 *
 * @param {Buffer|string} buffer File buffer or string
 * @param {string} category 'core' | 'bau' | 'montreal'
 */
function parseAndApplyExcel(buffer, category = 'core') {
  const targetCategory = ['core', 'bau', 'montreal'].includes(category) ? category : 'core';
  const csvText = Buffer.isBuffer(buffer) ? buffer.toString('utf8') : String(buffer);
  const rows = parseCsvString(csvText);

  if (!rows || rows.length === 0) {
    throw new Error('Rota CSV contains no data rows.');
  }

  const allRotas = loadAllRotas();
  const currentRota = allRotas[targetCategory] || emptyRotas()[targetCategory];

  currentRota.tableRows = rows;
  currentRota.month = rows[0]?.['Month'] || currentRota.month || 'Full Month';

  allRotas[targetCategory] = currentRota;
  saveAllRotas(allRotas);
  return allRotas;
}

/**
 * Generates a full month CSV template buffer for a given rota category (T0.19 / D7).
 * Retains signature and buffer return for caller compatibility.
 */
function generateExcelTemplate(category = 'core') {
  const targetCategory = ['core', 'bau', 'montreal'].includes(category) ? category : 'core';
  const allRotas = loadAllRotas();
  const rota = allRotas[targetCategory] || emptyRotas()[targetCategory];
  const rows = rota.tableRows && rota.tableRows.length ? rota.tableRows : blankMonthTemplate(targetCategory);

  const csvString = serializeToCsv(rows);
  return Buffer.from(csvString, 'utf8');
}

module.exports = {
  getAllRotas() {
    return loadAllRotas();
  },
  getRota(category = 'core') {
    const all = loadAllRotas();
    return all[category] || all.core;
  },
  updateRota(category, updatedData) {
    const targetCategory = ['core', 'bau', 'montreal'].includes(category) ? category : 'core';
    const all = loadAllRotas();
    all[targetCategory] = { ...all[targetCategory], ...updatedData };
    saveAllRotas(all);
    return all;
  },
  addShift(category, shiftRow) {
    const targetCategory = ['core', 'bau', 'montreal'].includes(category) ? category : 'core';
    const all = loadAllRotas();
    all[targetCategory].tableRows = all[targetCategory].tableRows || [];
    all[targetCategory].tableRows.push({
      "Date": shiftRow.Date || new Date().toISOString().split('T')[0],
      "Day": shiftRow.Day || 'Mon',
      "Shift ID": `${targetCategory.toUpperCase()}-SHIFT-${Date.now()}`,
      "Shift Name": shiftRow.shiftName || shiftRow['Shift Name'] || 'Scheduled Shift',
      "Primary On-Call": shiftRow.primaryOnCall || shiftRow['Primary On-Call'] || 'TBD',
      "Secondary On-Call": shiftRow.secondaryOnCall || shiftRow['Secondary On-Call'] || '—',
      "Escalation Manager": shiftRow.escalationManager || shiftRow['Escalation Manager'] || '—',
      "Location / Hub": shiftRow['Location / Hub'] || 'Global',
      "Status": "Scheduled",
      "Handover Notes": shiftRow['Handover Notes'] || ''
    });
    saveAllRotas(all);
    return all;
  },
  parseAndApplyExcel,
  generateExcelTemplate,
  serializeToCsv,
  parseCsvString
};
